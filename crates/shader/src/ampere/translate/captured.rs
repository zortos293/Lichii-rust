//! Instructions captured from Switch 2 titles, from the reference emulator's Ampere tests
//! (`src/tests/video_core/ampere_*.cpp`, named by file). Each translates in one stage or
//! another; branches and task/mesh stage buffer accesses, which need a control flow graph or
//! mesh state, are covered by their own tests.

use super::tests::translate_stage;
use crate::ShaderStage;
use crate::ampere::instruction::Instruction;

const STAGES: [ShaderStage; 7] = [
    ShaderStage::Fragment,
    ShaderStage::Compute,
    ShaderStage::VertexA,
    ShaderStage::VertexB,
    ShaderStage::Geometry,
    ShaderStage::TessellationControl,
    ShaderStage::TessellationEval,
];

fn instruction(words: [u32; 4]) -> Instruction {
    Instruction(
        u128::from(words[0])
            | u128::from(words[1]) << 32
            | u128::from(words[2]) << 64
            | u128::from(words[3]) << 96,
    )
}

fn translates(words: [u32; 4]) -> bool {
    let insn = instruction(words);
    STAGES
        .iter()
        .any(|&stage| translate_stage(stage, &[insn]).is_ok())
}

#[test]
fn captured_instructions_translate() {
    let failed: Vec<_> = CAPTURED
        .iter()
        .filter(|&&(_, words)| !translates(words))
        .collect();
    assert!(failed.is_empty(), "{failed:#x?}");
}

#[test]
fn malformed_captured_variants_are_rejected() {
    for (reason, words) in REJECTED {
        assert!(!translates(words), "{reason}: {words:#x?}");
    }
}

